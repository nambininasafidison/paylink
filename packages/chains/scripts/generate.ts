/** The six state-changing entry points, in ABI order of the spec's interface (§3.3.2). */
export const GAS_FUNCTIONS: readonly PayLinkFunction[] = [
  "payWithAuthorization",
  "pay",
  "payWithPermit",
  "payNative",
  "cancel",
  "cancelBySig",
];

/** Snapshot entries kept for reference but not turned into limits. */
const INFORMATIONAL = new Set(["deploy", "statesOf"]);
/** Variants measured with an EOA payee: they set the floor. */
const EOA_VARIANTS = new Set(["", "first", "repeat"]);
/** Variant measured with an ERC-1271 payee: it must fit under the ceiling (spec §3.3.6). */
const CONTRACT_PAYEE_VARIANT = "erc1271Payee";

/** Margin that clients add to `eth_estimateGas` (spec §3.3.6: × 1.10), as a fraction. */
export const ESTIMATE_MARGIN = { numerator: 110n, denominator: 100n } as const;
/** Ceiling = 1.5 × floor (spec §3.3.6), as a fraction. */
export const CEILING_FACTOR = { numerator: 3n, denominator: 2n } as const;
/** Limits are rounded up to this granularity. */
export const ROUNDING = 1000n;

const ceilDiv = (a: bigint, b: bigint): bigint => (a + b - 1n) / b;
const roundUp = (value: bigint): bigint => ceilDiv(value, ROUNDING) * ROUNDING;

export interface DerivedGas {
  readonly measurements: ReadonlyMap<string, bigint>;
  readonly limits: ReadonlyMap<PayLinkFunction, { floor: bigint; ceiling: bigint }>;
}

/**
 * Derives the per-function gas bounds from a Foundry gas snapshot (spec §3.3.6):
 * - floor = the largest EOA-payee measurement of the function (first and repeat payments), rounded up to 1,000;
 * - ceiling = 1.5 × floor, rounded up to 1,000;
 * - every ERC-1271-payee measurement, plus the 10 % estimate margin, must fit under the ceiling.
 * Unknown entries fail loudly, so a new snapshot entry is always mapped on purpose.
 */
export function deriveGasBounds(snapshot: Readonly<Record<string, unknown>>): DerivedGas {
  const measurements = new Map<string, bigint>();
  const eoa = new Map<PayLinkFunction, bigint>();
  const contractPayee = new Map<PayLinkFunction, bigint>();
  const functions = new Set<string>(GAS_FUNCTIONS);

  for (const name of Object.keys(snapshot).sort()) {
    const raw = snapshot[name];
    if (typeof raw !== "string" || !/^[1-9][0-9]{0,15}$/.test(raw)) {
      throw new Error(`gas snapshot: ${name} must be a positive decimal string, got ${JSON.stringify(raw)}`);
    }
    const gas = BigInt(raw);
    measurements.set(name, gas);
    const separator = name.indexOf("_");
    const fn = separator === -1 ? name : name.slice(0, separator);
    const variant = separator === -1 ? "" : name.slice(separator + 1);
    if (INFORMATIONAL.has(fn)) {
      continue;
    }
    if (!functions.has(fn)) {
      throw new Error(`gas snapshot: unknown entry ${name} (map it in scripts/generate.ts)`);
    }
    const key = fn as PayLinkFunction;
    if (EOA_VARIANTS.has(variant)) {
      const previous = eoa.get(key) ?? 0n;
      eoa.set(key, gas > previous ? gas : previous);
    } else if (variant === CONTRACT_PAYEE_VARIANT) {
      contractPayee.set(key, gas);
    } else {
      throw new Error(`gas snapshot: unknown variant ${name} (map it in scripts/generate.ts)`);
    }
  }

  const limits = new Map<PayLinkFunction, { floor: bigint; ceiling: bigint }>();
  for (const fn of GAS_FUNCTIONS) {
    const measured = eoa.get(fn);
    if (measured === undefined) {
      throw new Error(`gas snapshot: no EOA-payee measurement for ${fn}`);
    }
    const floor = roundUp(measured);
    const ceiling = roundUp(ceilDiv(floor * CEILING_FACTOR.numerator, CEILING_FACTOR.denominator));
    const worst = contractPayee.get(fn);
    if (worst !== undefined) {
      const needed = ceilDiv(worst * ESTIMATE_MARGIN.numerator, ESTIMATE_MARGIN.denominator);
      if (needed > ceiling) {
        throw new Error(`gas snapshot: ${fn} ERC-1271 payee needs ${needed} gas with the margin, above the ceiling ${ceiling}`);
      }
    }
    limits.set(fn, { floor, ceiling });
  }
  return { measurements, limits };
}

const gasLiteral = (value: bigint): string => `${value.toString().replace(/\B(?=(\d{3})+(?!\d))/g, "_")}n`;

/** One scenario measured on an anvil node: the smallest working gas limit and the receipt's gas used. */
export interface Measurement {
  readonly estimate: number;
  readonly gasUsed: number;
}

export interface MeasuredProfile {
  readonly chainId: number;
  readonly hardfork: string;
  readonly network: string;
  readonly appliesTo: readonly number[];
  readonly measurements: Readonly<Record<string, Measurement>>;
}

export interface MeasurementsFile {
  readonly tool: string;
  readonly profiles: Readonly<Record<string, MeasuredProfile>>;
}

/**
 * Profiles whose gas schedule differs from Ethereum's, so that their own estimates define the bounds of the
 * chains they apply to. Monad: cold SLOAD 8,100, cold account 10,100, ecrecover 6,000, and the gas limit
 * is charged (spec §3.3.6). Every other profile must fit under the snapshot bounds.
 */
export const EMULATED_PROFILES: ReadonlySet<string> = new Set(["monad"]);

const positive = (value: unknown): value is number => typeof value === "number" && Number.isSafeInteger(value) && value > 0;

/** Validates data/gas-measurements.json (written by packages/sdk/scripts/measure-gas.ts) against the release. */
export function parseMeasurements(text: string, initCodeHash: string): MeasurementsFile {
  const file = JSON.parse(text) as Record<string, unknown>;
  expect(file["schema"] === "paylink.gas-measurements/1", "gas measurements: schema must be paylink.gas-measurements/1");
  expect(file["initCodeHash"] === initCodeHash, "gas measurements: measured on another build than release.json (re-run measure-gas.ts)");
  expect(typeof file["tool"] === "string", "gas measurements: tool missing");
  const profiles = file["profiles"] as Record<string, Record<string, unknown>>;
  for (const [name, profile] of Object.entries(profiles)) {
    expect(positive(profile["chainId"]) && typeof profile["hardfork"] === "string" && typeof profile["network"] === "string", `gas measurements: profile ${name}`);
    const appliesTo = profile["appliesTo"];
    expect(Array.isArray(appliesTo) && appliesTo.every(positive), `gas measurements: profile ${name} appliesTo`);
    for (const [scenario, m] of Object.entries(profile["measurements"] as Record<string, Record<string, unknown>>)) {
      expect(positive(m["estimate"]) && positive(m["gasUsed"]), `gas measurements: ${name}.${scenario} needs positive estimate and gasUsed`);
    }
  }
  return { tool: file["tool"], profiles: profiles as unknown as Record<string, MeasuredProfile> };
}

/** Bounds derived from a profile's estimates, with the same rule as the snapshot. */
export function deriveEmulatedBounds(profile: MeasuredProfile): DerivedGas {
  return deriveGasBounds(Object.fromEntries(Object.entries(profile.measurements).map(([name, m]) => [name, String(m.estimate)])));
}

/**
 * Throws when a measured transaction could not be sent within `limits`: its estimate plus the 10 % margin
 * must fit under the ceiling of its function.
 */
export function checkCoverage(profileName: string, profile: MeasuredProfile, limits: ReadonlyMap<PayLinkFunction, { floor: bigint; ceiling: bigint }>): void {
  for (const [scenario, m] of Object.entries(profile.measurements)) {
    const fn = scenario.split("_")[0] as PayLinkFunction;
    const bounds = limits.get(fn);
    expect(bounds !== undefined, `gas measurements: ${profileName}.${scenario} has no function bounds`);
    const needed = ceilDiv(BigInt(m.estimate) * ESTIMATE_MARGIN.numerator, ESTIMATE_MARGIN.denominator);
    expect(needed <= bounds.ceiling, `gas measurements: ${profileName}.${scenario} needs ${needed} gas with the margin, above the ceiling ${bounds.ceiling}`);
  }
}

const renderBounds = (limits: ReadonlyMap<PayLinkFunction, { floor: bigint; ceiling: bigint }>, indent: string): string =>
  GAS_FUNCTIONS.map((fn) => {
    const b = limits.get(fn);
    if (b === undefined) {
      throw new Error(`unreachable: ${fn}`);
    }
    return `${indent}${fn}: { floor: ${gasLiteral(b.floor)}, ceiling: ${gasLiteral(b.ceiling)} },`;
  }).join("\n");

export function renderGas(snapshotText: string, measurementsText: string, initCodeHash: string): string {
  const snapshot = JSON.parse(snapshotText) as Record<string, unknown>;
  const { measurements, limits } = deriveGasBounds(snapshot);
  const measured = parseMeasurements(measurementsText, initCodeHash);
  const emulated: string[] = [];
  const profiles: string[] = [];
  for (const [name, profile] of Object.entries(measured.profiles).sort(([a], [b]) => a.localeCompare(b))) {
    if (EMULATED_PROFILES.has(name)) {
      const derived = deriveEmulatedBounds(profile);
      checkCoverage(name, profile, derived.limits);
      emulated.push(`  ${name}: {\n${renderBounds(derived.limits, "    ")}\n  },`);
    } else {
      checkCoverage(name, profile, limits);
    }
    const rows = Object.entries(profile.measurements)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([scenario, m]) => `      ${scenario}: { estimate: ${m.estimate}, gasUsed: ${m.gasUsed} },`)
      .join("\n");
    profiles.push(
      `  ${name}: {\n    chainId: ${profile.chainId},\n    hardfork: ${JSON.stringify(profile.hardfork)},\n    network: ${JSON.stringify(profile.network)},\n    appliesTo: [${profile.appliesTo.join(", ")}],\n    measurements: {\n${rows}\n    },\n  },`,
    );
  }
  const snapshotRows = [...measurements].map(([name, gas]) => `  ${name}: ${gasLiteral(gas)},`).join("\n");
  return `${HEADER(`${SOURCES.gasSnapshot} and ${SOURCES.gasMeasurements}`)}//
// Rule (PAYLINK-V2-SPEC §3.3.6): floor = the largest EOA-payee measurement of the function (first and repeat
// payments), ceiling = 1.5 x floor, both rounded up to the next 1,000 gas. Each ERC-1271-payee measurement plus
// the 10 % estimate margin fits under the ceiling.
// - Snapshot bounds: Foundry in-test gas with Ethereum prices against mock tokens (protocol/audit/gas.md). The
//   generator refuses them unless every eth_estimateGas measured on the Ethereum-priced anvil profiles (Ethereum,
//   Base, London for Mezo) plus 10 % fits under the ceiling.
// - Emulated bounds (Monad): the same rule applied to eth_estimateGas on anvil's Monad emulation (MonadTen),
//   because Monad prices cold state and ecrecover differently and charges the gas limit.
// Both are provisional until re-measured on each testnet with cold slots and the real tokens.
import type { GasBounds, PayLinkFunction } from "../types.ts";

/** Raw per-call gas measurements written by \`protocol/test/gas/Gas.t.sol\`. */
export const GAS_SNAPSHOT_MEASUREMENTS = {
${snapshotRows}
} as const;

/** Gas-limit bounds derived from the snapshot (Ethereum gas prices). */
export const SNAPSHOT_GAS_LIMITS: Readonly<Record<PayLinkFunction, GasBounds>> = {
${renderBounds(limits, "  ")}
};

/** eth_estimateGas and receipt gasUsed per scenario, on anvil nodes emulating each network (${measured.tool}). */
export const GAS_MEASUREMENTS = {
${profiles.join("\n")}
} as const;

/** Gas-limit bounds of the networks whose gas schedule differs from Ethereum's, from their own estimates. */
export const EMULATED_GAS_LIMITS = {
${emulated.join("\n")}
} as const satisfies Readonly<Record<string, Readonly<Record<PayLinkFunction, GasBounds>>>>;
`;
}

