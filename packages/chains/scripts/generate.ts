export interface V1Config {
  readonly network: string;
  readonly chainId: number;
  readonly rpc: string;
  readonly explorer: string | null;
  readonly address: `0x${string}` | null;
}

/** Reads the JSON object literal that `web/config.js` assigns to `window.PAYLINK_CONFIG`. */
export function parseV1Config(text: string): V1Config {
  const match = /window\.PAYLINK_CONFIG\s*=\s*(\{[\s\S]*?\});/.exec(text);
  expect(match?.[1] !== undefined, "web/config.js: window.PAYLINK_CONFIG = {...}; not found");
  const c = JSON.parse(match[1]) as Record<string, unknown>;
  expect(typeof c["chainId"] === "number" && Number.isSafeInteger(c["chainId"]), "web/config.js: chainId");
  expect(typeof c["network"] === "string", "web/config.js: network");
  expect(typeof c["rpc"] === "string" && c["rpc"].startsWith("https://"), "web/config.js: rpc must be https");
  expect(c["explorer"] === null || (typeof c["explorer"] === "string" && c["explorer"].startsWith("https://")), "web/config.js: explorer");
  const address = c["address"] === null ? null : checksummed(c["address"], "web/config.js address");
  return { network: c["network"], chainId: c["chainId"], rpc: c["rpc"], explorer: c["explorer"], address };
}

export function renderV1(text: string): string {
  const c = parseV1Config(text);
  return `${HEADER(SOURCES.v1Config)}
/** The frozen v1 app's network configuration (Arc Microgrants entry, ADR 0010). \`address\` stays null until v1 is deployed. */
export const V1_CONFIG = {
  network: ${JSON.stringify(c.network)},
  chainId: ${c.chainId},
  rpc: ${JSON.stringify(c.rpc)},
  explorer: ${JSON.stringify(c.explorer)},
  address: ${JSON.stringify(c.address)},
} as const;
`;
}

