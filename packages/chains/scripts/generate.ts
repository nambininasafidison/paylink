/** Renders every generated file from the repository at `repoDir`. Keys are paths relative to the package. */
export function renderAll(repoDir: string = REPO_DIR): ReadonlyMap<string, string> {
  const read = (relative: string): string => readFileSync(join(repoDir, relative), "utf8");
  const releaseText = read(SOURCES.release);
  const release = parseRelease(releaseText);
  const records = readdirSync(join(repoDir, SOURCES.deploymentsDir))
    .filter((name) => /^[1-9][0-9]*\.json$/.test(name))
    .map((name) => parseDeploymentRecord(read(`${SOURCES.deploymentsDir}/${name}`), Number(name.slice(0, -5)), release));
  return new Map([
    ["src/generated/gas.ts", renderGas(read(SOURCES.gasSnapshot), read(SOURCES.gasMeasurements), release.bytecode.initCodeHash)],
    ["src/generated/release.ts", renderRelease(releaseText)],
    ["src/generated/deployments.ts", renderDeployments(records)],
    ["src/generated/v1.ts", renderV1(read(SOURCES.v1Config))],
  ]);
}

// Command-line driver; the renderers above are unit-tested through test/generated.test.ts.
function main(argv: readonly string[]): number {
  const check = argv.includes("--check");
  let stale = 0;
  for (const [relative, content] of renderAll()) {
    const path = join(PACKAGE_DIR, relative);
    let current: string;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = "";
    }
    if (current === content) {
      continue;
    }
    if (check) {
      stale += 1;
      console.error(`stale: ${relative} (run: node scripts/generate.ts)`);
    } else {
      writeFileSync(path, content);
      console.log(`wrote ${relative}`);
    }
  }
  return stale === 0 ? 0 : 1;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
