const HEX32 = /^0x[0-9a-f]{64}$/;

function expect(condition: boolean, message: string): asserts condition {
  if (!condition) {
    throw new Error(message);
  }
}

function checksummed(value: unknown, field: string): `0x${string}` {
  expect(typeof value === "string" && /^0x[0-9a-fA-F]{40}$/.test(value), `${field}: not an address`);
  const address = getAddress(value);
  expect(address === value, `${field}: ${value} is not EIP-55 checksummed (expected ${address})`);
  return address;
}

function hash32(value: unknown, field: string): `0x${string}` {
  expect(typeof value === "string" && HEX32.test(value) && isHex(value), `${field}: not a lowercase bytes32`);
  return value;
}

interface ReleaseRecord {
  readonly release: string;
  readonly bytecode: {
    readonly initCodeHash: string;
    readonly initCodeSize: number;
    readonly maskedRuntimeHash: string;
    readonly runtimeCodeSize: number;
    readonly immutableReferences: readonly { readonly start: number; readonly length: number }[];
    readonly cborMetadata: string;
  };
  readonly compiler: { readonly solc: string; readonly evmVersion: string; readonly settingsHash: string };
  readonly dependencies: Readonly<Record<string, string>>;
  readonly create2: { readonly factory: string; readonly salt: string; readonly saltPreimage: string; readonly address: string };
}

export function parseRelease(text: string): ReleaseRecord {
  const r = JSON.parse(text) as Record<string, unknown> & ReleaseRecord;
  expect(r["schema"] === "paylink.release/1", "release.json: schema must be paylink.release/1");
  expect(r["contract"] === "PayLinkV2", "release.json: contract must be PayLinkV2");
  expect(typeof r.release === "string" && /^\d+\.\d+\.\d+$/.test(r.release), "release.json: release must be semver");
  hash32(r.bytecode.initCodeHash, "release.bytecode.initCodeHash");
  hash32(r.bytecode.maskedRuntimeHash, "release.bytecode.maskedRuntimeHash");
  hash32(r.compiler.settingsHash, "release.compiler.settingsHash");
  hash32(r.create2.salt, "release.create2.salt");
  checksummed(r.create2.factory, "release.create2.factory");
  checksummed(r.create2.address, "release.create2.address");
  expect(/^0x[0-9a-f]+$/.test(r.bytecode.cborMetadata), "release.bytecode.cborMetadata: not lowercase hex");
  for (const ref of r.bytecode.immutableReferences) {
    expect(Number.isSafeInteger(ref.start) && ref.start >= 0 && ref.length === 32, "release: bad immutable reference");
  }
  return r;
}

export function renderRelease(text: string): string {
  const r = parseRelease(text);
  const refs = r.bytecode.immutableReferences.map((x) => `    { start: ${x.start}, length: ${x.length} },`).join("\n");
  return `${HEADER(SOURCES.release)}
/** Identity of the audited PayLinkV2 release artifact (protocol/deployments/README.md). */
export const RELEASE = {
  contract: "PayLinkV2",
  release: ${JSON.stringify(r.release)},
  initCodeHash: ${JSON.stringify(r.bytecode.initCodeHash)},
  initCodeSize: ${r.bytecode.initCodeSize},
  maskedRuntimeHash: ${JSON.stringify(r.bytecode.maskedRuntimeHash)},
  runtimeCodeSize: ${r.bytecode.runtimeCodeSize},
  /** Byte ranges of the seven OpenZeppelin EIP712 immutables in the runtime code, sorted by start. */
  immutableReferences: [
${refs}
  ],
  cborMetadata: ${JSON.stringify(r.bytecode.cborMetadata)},
  compiler: { solc: ${JSON.stringify(r.compiler.solc)}, evmVersion: ${JSON.stringify(r.compiler.evmVersion)}, settingsHash: ${JSON.stringify(r.compiler.settingsHash)} },
  openZeppelin: ${JSON.stringify(r.dependencies["@openzeppelin/contracts"])},
  create2: {
    factory: ${JSON.stringify(r.create2.factory)},
    salt: ${JSON.stringify(r.create2.salt)},
    saltPreimage: ${JSON.stringify(r.create2.saltPreimage)},
    address: ${JSON.stringify(r.create2.address)},
  },
} as const;
`;
}

